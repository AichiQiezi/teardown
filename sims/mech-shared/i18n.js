const TABLES = {en: EN, zh: ZH};
const KEY = 'gipsy-lang';
const pick = () => {
  const q = new URLSearchParams(location.search).get('lang');
  if (q in TABLES) return q;
  try {
    const s = localStorage.getItem(KEY);
    if (s in TABLES) return s;
  } catch {}
  return /^zh/i.test(navigator.language || '') ? 'zh' : 'en';
};

let lang = pick();
const listeners = [];
export const getLang = () => lang;
export const t = (k, ...a) => {
  const v = TABLES[lang][k] ?? EN[k];
  return typeof v === 'function' ? v(...a) : v;
};
/** Switches language, remembers it, and tells whoever relabels static text. */
export const setLang = (l) => {
  lang = l;
  try {
    localStorage.setItem(KEY, l);
  } catch {}
  document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en';
  for (const f of listeners) f(l);
};
export const onLang = (f) => listeners.push(f);
document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
